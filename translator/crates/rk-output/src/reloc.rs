//! Writes the relocatable-body archive: translated bodies plus the immutable template table.

use std::fmt::Write as _;
use std::path::Path;

use rk_core::{Addr, Error, Result};
use rk_emit::{Body, Preludes};

pub const CHUNK_SOURCE_BUDGET: usize = 4 * 1024 * 1024;

const SEH_CALL_HELPER: &str = "\
static void recomp_seh_frame_call_(X86 *c, void (*next)(X86 *), int adopt) {
jmp_buf *b = adopt ? recomp_seh_frame_adopt(c) : recomp_seh_frame_enter(c);
if (b && RECOMP_SETJMP(*b)) { recomp_seh_land(c); return; }
next(c);
}
";

pub struct Template {
    pub id: String,
    pub base: Addr,
    pub code: Vec<u8>,
    pub masked: Vec<u32>,
    pub imports: Vec<(u32, u32)>,
    pub entries: Vec<u32>,
    pub bodies: Vec<Body>,
}

pub struct Translation {
    pub templates: Vec<Template>,
    pub preludes: Preludes,
}

fn write_file(path: &Path, text: &str) -> Result<()> {
    std::fs::write(path, text).map_err(|e| Error::io(path, e))
}

fn hex_lines(data: &[u8]) -> String {
    let mut text = String::new();
    for chunk in data.chunks(24) {
        for byte in chunk {
            let _ = write!(text, "0x{byte:02x},");
        }
        text.push('\n');
    }
    text
}

fn body_chunk(translation: &Translation, bodies: &[&Body]) -> String {
    let mut text = String::from("/* generated by recomp-translate -- do not edit */\n#include \"body.h\"\n#include \"reloc.h\"\n");
    text.push_str(&translation.preludes.return_helpers);
    text.push_str(&translation.preludes.memory_helpers);
    text.push_str(&translation.preludes.float_helpers);
    if bodies.iter().any(|body| body.requires.seh_call) {
        text.push_str(SEH_CALL_HELPER);
    }
    for body in bodies {
        let _ = write!(
            text,
            "/* RELOC_{:08x}  {} insns  {:08x}..{:08x} */\n",
            body.addr, body.insns, body.first, body.last
        );
        text.push_str(&body.text);
        text.push_str("\n\n");
    }
    text
}

fn template_table(translation: &Translation) -> String {
    let mut text = String::from(
        "/* generated by recomp-translate -- do not edit */\n#include \"reloc.h\"\n\n",
    );
    for template in &translation.templates {
        for offset in &template.entries {
            let _ = writeln!(
                text,
                "void fn_{:08x}(X86 *c, uint32_t base_);",
                template.base + offset
            );
        }
    }
    text.push('\n');
    for (index, template) in translation.templates.iter().enumerate() {
        let label = format!("reloc_{index:03}");
        let _ = writeln!(text, "static const uint8_t {label}_code[] = {{");
        text.push_str(&hex_lines(&template.code));
        text.push_str("};\n");
        let _ = writeln!(text, "static const uint32_t {label}_masked[] = {{");
        for offset in &template.masked {
            let _ = writeln!(text, "0x{offset:x}u,");
        }
        if template.masked.is_empty() {
            text.push_str("0u,\n");
        }
        text.push_str("};\n");
        let _ = writeln!(
            text,
            "static const RecompRelocImport {label}_imports[] = {{"
        );
        for (slot, target) in &template.imports {
            let _ = writeln!(text, "{{0x{slot:x}u, 0x{target:08x}u}},");
        }
        if template.imports.is_empty() {
            text.push_str("{0u, 0u},\n");
        }
        text.push_str("};\n");
        let _ = writeln!(text, "static const RecompRelocEntry {label}_entries[] = {{");
        for offset in &template.entries {
            let func = template.base + offset;
            let _ = writeln!(text, "{{0x{offset:x}u, fn_{func:08x}}},");
        }
        if template.entries.is_empty() {
            text.push_str("{0u, 0},\n");
        }
        text.push_str("};\n");
    }
    text.push_str("static const RecompRelocTemplate recomp_reloc_templates[] = {\n");
    for (index, template) in translation.templates.iter().enumerate() {
        let label = format!("reloc_{index:03}");
        let name = serde_json::to_string(&template.id).unwrap_or_default();
        let _ = writeln!(
            text,
            "{{{name}, {label}_code, {}, {label}_masked, {}, {label}_imports, {}, {label}_entries, {}}},",
            template.code.len(),
            template.masked.len(),
            template.imports.len(),
            template.entries.len()
        );
    }
    if translation.templates.is_empty() {
        text.push_str("{0},\n");
    }
    text.push_str("};\n\n");
    let _ = writeln!(
        text,
        "static const uint32_t recomp_reloc_template_count = {};\n",
        translation.templates.len()
    );
    text.push_str(
        "__attribute__((constructor)) static void recomp_reloc_register_all(void)\n{\n    recomp_reloc_register(recomp_reloc_templates, recomp_reloc_template_count);\n}\n",
    );
    text
}

pub fn write(out: &Path, translation: &Translation) -> Result<()> {
    let reloc = out.join("reloc");
    std::fs::create_dir_all(&reloc).map_err(|e| Error::io(&reloc, e))?;
    let mut bodies: Vec<&Body> = translation
        .templates
        .iter()
        .flat_map(|template| template.bodies.iter())
        .collect();
    bodies.sort_by_key(|body| body.addr);
    let mut chunks: Vec<Vec<&Body>> = Vec::new();
    for body in bodies {
        let weight = body.text.len() + 1;
        match chunks.last_mut() {
            Some(chunk)
                if chunk.iter().map(|body| body.text.len() + 1).sum::<usize>() + weight
                    <= CHUNK_SOURCE_BUDGET =>
            {
                chunk.push(body);
            }
            _ => chunks.push(vec![body]),
        }
    }
    for (index, chunk) in chunks.iter().enumerate() {
        write_file(
            &reloc.join(format!("chunk_{index:03}.c")),
            &body_chunk(translation, chunk),
        )?;
    }
    write_file(&reloc.join("table.c"), &template_table(translation))
}
