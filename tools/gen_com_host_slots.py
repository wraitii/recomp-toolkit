#!/usr/bin/env python3
"""Generate the named host entry slot lists from the shared COM method catalog.

Each (dll, interface) in dx/metadata/com-methods.json becomes an X-macro
`COM_HOST_SLOTS_<stem>_<Interface>(X, ctx)` listing, per vtable slot, the
`rk_host_<stem>_<Interface>_<Method>` symbol the translator emits for guarded
direct calls, the slot index, the method name and the catalog argc. dx sources
expand it with COM_HOST_SLOTS (dx/com.h) beside the matching registration.
"""
import argparse
import json
from pathlib import Path
import re

IDENTIFIER = re.compile(r'^[A-Za-z0-9_]+$')


def render(catalog):
    interfaces = {}
    for row in catalog["methods"]:
        stem = row["dll"].lower().removesuffix(".dll")
        key = f'{stem}_{row["interface"]}'
        if not IDENTIFIER.match(key) or not IDENTIFIER.match(row["method"]):
            raise ValueError(f'{row["dll"]}!{row["interface"]}::{row["method"]} is not an identifier')
        interfaces.setdefault(key, []).append(row)
    lines = ['// Generated by tools/gen_com_host_slots.py; do not edit.',
             f'// Catalog reference SHA256: {catalog["reference_sha256"]}', '']
    for key, rows in interfaces.items():
        rows.sort(key=lambda row: row["slot"])
        if [row["slot"] for row in rows] != list(range(0, 4 * len(rows), 4)):
            raise ValueError(f'{key} slots are not dense')
        lines.append(f'#define COM_HOST_SLOTS_{key}(X, ctx) \\')
        lines += [f'    X(ctx, rk_host_{key}_{row["method"]}, {row["slot"] // 4}, "{row["method"]}", '
                  f'{row["argc"]}) \\' for row in rows]
        lines.append('')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    try:
        text = render(json.loads(args.catalog.read_text()))
    except (ValueError, OSError, KeyError) as failure:
        parser.error(str(failure))
    if not args.output.exists() or args.output.read_text() != text:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)


if __name__ == '__main__':
    main()
